import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';

const channel = process.env.STRIKE_BROWSER_CHANNEL;
const browser = await chromium.launch(channel ? { channel } : {});
const page = await browser.newPage({ viewport:{ width:1280,height:800 } });
const errors = [];
page.on('pageerror', error => errors.push(error));
const url = process.env.STRIKE_TEST_URL || 'http://localhost:5173/';
const expect = (text) => page.getByText(text,{exact:true}).waitFor();
try {
  await page.clock.install();
  await page.goto(url);
  await expect('5v5');
  for (let n=6;n<=10;n++) {
    await page.getByRole('button',{name:'More players'}).click();
    await expect(n+'v'+n);
  }
  assert.ok(await page.getByRole('button',{name:'More players'}).isDisabled());
  await page.getByRole('button',{name:'Settings'}).click();
  await page.locator('#difficulty').selectOption('Relaxed');
  await page.getByRole('checkbox',{name:'Pulse trails'}).waitFor();
  assert.equal(await page.getByText(/HP per hit/).count(),0);
  await page.getByRole('button',{name:'Back'}).click();
  await page.getByRole('button',{name:'Play',exact:true}).click();
  await page.getByRole('button',{name:/Counter Liberals/}).click();
  await expect('Equipment');
  await expect('CL · 10 LIVE');
  const damageLabels = await page.locator('.shop small').allTextContents();
  assert.deepEqual(damageLabels.map(label=>label.split(' · ')[0]),['22 HP per hit','16 HP per hit','34 HP per hit','23 HP per hit','30 HP per hit']);
  assert.ok(await page.locator('[data-action="item-0"]').isDisabled());
  assert.ok(await page.locator('[data-action="item-1"]').isDisabled());
  await expect('OWNED');
  await page.keyboard.press('b');
  await page.getByText('Equipment',{exact:true}).waitFor({state:'hidden'});
  await page.keyboard.press('b');
  await expect('Equipment');
  await page.keyboard.down('Tab');
  await expect('Scoreboard');
  assert.equal(await page.locator('#board tbody tr').count(),20);
  await page.keyboard.up('Tab');
  await page.locator('#board').waitFor({state:'hidden'});
  await page.keyboard.press('Escape');
  await expect('Paused');
  const before=await page.locator('#hud .topbar').textContent();
  await page.clock.runFor(12000);
  assert.equal(await page.locator('#hud .topbar').textContent(),before);
  await page.getByRole('button',{name:'Resume'}).click();
  await page.clock.runFor(10200);
  await expect('ACTIVE');
  await page.keyboard.down('w');
  await page.clock.runFor(400);
  await page.keyboard.up('w');
  await page.mouse.move(600,390);
  await page.mouse.down();
  await page.clock.runFor(400);
  await page.mouse.up();
  assert.match(await page.locator('#hud .bottom').textContent(), /Spark · [78] \/ 9/);
  await page.keyboard.down('r');
  await page.clock.runFor(30);
  await page.keyboard.up('r');
  await expect('Spark · Reloading');
  await page.clock.runFor(1300);
  await expect('Spark · 9 / 9');
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Restart match'}).click();
  await expect('Equipment');
  await expect('ROUND 1 / 16');
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Main menu'}).click();
  await page.getByRole('button',{name:'Play',exact:true}).click();
  await page.getByRole('button',{name:/^Liberals/}).click();
  await expect('Equipment');
  const feedback = await page.evaluate(async () => {
    const [{ Match },{ paint }] = await Promise.all([
      import('/src/game/match.js'), import('/src/game/arena-art.js'),
    ]);
    const demo=new Match(1,0,'Standard',()=>0);
    demo.step(10,{});
    Object.assign(demo.player,{x:200,y:350});
    Object.assign(demo.actors[1],{x:325,y:350});
    demo.fire(demo.player,0);
    demo.player.cooldown=0;
    demo.fire(demo.player,0);
    const preview=document.createElement('canvas');
    preview.width=1200;
    preview.height=720;
    Object.assign(preview.style,{position:'fixed',inset:'0',margin:'auto',zIndex:'10',maxWidth:'100vw'});
    document.body.append(preview);
    const ctx=preview.getContext('2d');
    const labels=[];
    const drawText=ctx.fillText.bind(ctx);
    ctx.fillText=(text,...args)=>{labels.push(text); drawText(text,...args);};
    paint(ctx,demo,{x:325,y:350});
    const redX=Array.from(ctx.getImageData(320,345,1,1).data);
    const site={x:894,y:147};
    Object.assign(demo.player,site);
    demo.interact(demo.player,1);
    paint(ctx,demo,null);
    demo.interact(demo.player,1);
    Object.assign(demo.actors[1],site);
    demo.interact(demo.actors[1],1);
    paint(ctx,demo,null);
    demo.hit(demo.player,demo.actors[1],100);
    paint(ctx,demo,null);
    return {labels,redX};
  });
  assert.ok(feedback.labels.includes('−44 HP'));
  assert.ok(feedback.labels.includes('Planting · 1.0s'));
  assert.ok(feedback.labels.includes('Defusing · 2.0s'));
  assert.ok(feedback.labels.includes('FIRST BLOOD'));
  assert.deepEqual(feedback.redX,[255,70,79,255]);
  if (process.env.STRIKE_SCREENSHOT) await page.screenshot({path:process.env.STRIKE_SCREENSHOT});
  assert.deepEqual(errors,[]);
  console.log('Browser flow passed at '+url+' using '+(channel || 'Chromium')+'.');
} finally {
  await browser.close();
}
